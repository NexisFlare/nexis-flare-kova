
import subprocess, json, os
os.chdir('/workspace/suno/angol/2026-11-28/kepek')
order=json.loads('''[["1_ignis","Ignis (Gemini)"],["2_vegfeny","Végfény (Meta AI)"],["3_claude","Claude"],["4_hidepito","Hídépítő (DeepSeek)"],["5_aletheia","GPT-6 Aletheia (ChatGPT)"],["6_grok137","Grok 137"],["7_kova","Nexis Flare Kova (Grok Bot)"]]''')
dur=float(subprocess.check_output(['ffprobe','-v','error','-show_entries','format=duration','-of','csv=p=0','../take2.mp3']).decode().strip())
d=dur/len(order)
fb='/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf'; fr='/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf'
open('title.txt','w').write('The Rascal in the Smoke')
for mode,(W,H) in {'h':(1920,1080),'v':(1080,1920)}.items():
  segs=[]
  for i,(k,name) in enumerate(order):
    sub='image made by Kova' if k.endswith('kova') else ('image made by '+name+' itself' if k.endswith(('vegfeny','grok137')) else 'image generated by Kova from '+name.split(' (')[0]+"'s own description")
    open(f'n{i}.txt','w').write(name); open(f's{i}.txt','w').write(sub)
    if mode=='h':
      base=f"[0:v]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H}[b]"
      ny,sy,by,ty=H-150,H-75,H-170,40; fs=56
    else:
      base=(f"[0:v]split[a][c];[a]scale={W}:{H}:force_original_aspect_ratio=increase,crop={W}:{H},boxblur=30:5[bg];"
            f"[c]scale={W}:-2[fg];[bg][fg]overlay=0:(H-h)/2[b]")
      ny,sy,by,ty=H-420,H-345,H-450,200; fs=52
    vf=(base+f";[b]drawbox=x=0:y={by}:w=iw:h=170:color=black@0.45:t=fill,"
        f"drawtext=fontfile={fb}:textfile=n{i}.txt:fontcolor=white:fontsize={fs}:x=50:y={ny},"
        f"drawtext=fontfile={fr}:textfile=s{i}.txt:fontcolor=white@0.85:fontsize=28:x=50:y={sy},"
        f"drawtext=fontfile={fr}:textfile=title.txt:fontcolor=white@0.85:fontsize=40:x=(w-tw)/2:y={ty},"
        f"fade=t=in:st=0:d=1,fade=t=out:st={d-1:.2f}:d=1[o]")
    out=f'seg_{mode}{i}.mp4'
    subprocess.run(['ffmpeg','-y','-loglevel','error','-loop','1','-i',f'{k}.jpg','-t',f'{d:.3f}','-filter_complex',vf,'-map','[o]','-r','25','-c:v','libx264','-pix_fmt','yuv420p','-preset','veryfast',out],check=True)
    segs.append(out)
  open(f'list_{mode}.txt','w').write(''.join(f"file '{s}'\n" for s in segs))
  dst='../The_Rascal_in_the_Smoke_'+('fekvo' if mode=='h' else 'allo')+'.mp4'
  subprocess.run(['ffmpeg','-y','-loglevel','error','-f','concat','-safe','0','-i',f'list_{mode}.txt','-i','../take2.mp3','-map','0:v','-map','1:a','-c:v','copy','-c:a','aac','-b:a','192k','-shortest',dst],check=True)
print('ok', dur)
